/** 按 id 取风格，未命中回退到默认。 */
export function getStyle(id) {
  return STYLES.find((s) => s.id === id) ?? STYLES[0];
}

/**
 * 意图 → 风格自动识别（确定性关键词路由，零额外 LLM 调用）。
 * 命中关键词最多的风格胜出；无命中回退默认风格。
 * 团队要调整识别规则：只改上面每个风格的 keywords 数组即可。
 */
export function detectStyle(prompt) {
  const p = String(prompt ?? "");
  let best = STYLES[0];
  let bestScore = 0;
  for (const s of STYLES) {
    let score = 0;
    for (const kw of s.keywords) if (p.includes(kw)) score++;
    if (score > bestScore) {
      best = s;
      bestScore = score;
    }
  }
  return best;
}
